"""Deterministic caption-field parser: free text -> structured fields.

The Bang & Kim captions follow one grammar (verified on all 735 distinct normalised
captions, see PLAN.md section 2)::

    [COUNT] [pile of] [COLOUR] RESOURCE [is|are] PREDICATE
      "Two orange excavators are digging soil"
      "A pile of black H-beam are located on soil"
      "Fences are installed in a line"

    PREDICATE := VERB [PREP] TARGET [PREP TARGET2]
      located|installed|embedded|placed (on|in) TARGET
      digging|lifting|pouring TARGET          loaded|covered [with] TARGET
      drilling on TARGET     putting TARGET (in|on) TARGET2     empty     on TARGET

Design rules (so every line can be defended):

* **Strict, not clever.** The parser either explains a caption completely or reports why it
  could not. Nothing is guessed: words outside the reviewed vocabulary, two clauses glued
  together ("...soilA black dust..."), or a missing resource all give an explicit failure reason.
* **Repairs are an explicit, reviewed table** (:data:`TOKEN_REPAIRS`, :data:`PHRASE_REPAIRS`)
  limited to unambiguous typos seen in the data ("sturcture", "rebara", "wo workers").
  Each applied repair is recorded in ``fields["repairs"]`` so the audit can see it.
* **Coverage is a reported number**, never assumed (``CoverageReport``).

``count`` semantics: ``a``/``an`` -> 1; a number word -> that integer; no determiner (e.g.
"Fences are installed", "Concrete is installed") -> ``None`` (unknown, not 0 or 1).
``count_unit`` is ``"pile"`` for "a pile of X" / "two piles of X" and ``"item"`` otherwise: the
count then refers to piles, not individual objects.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from sitesight.data.schema import FLAG_UNPARSED, CategoryRecord, Dataset

# Vocabulary, reviewed by hand against all 735 distinct captions.

COLOURS = frozenset(
    {"black", "blue", "brown", "gray", "grey", "green", "orange", "pink", "purple"}
    | {"red", "silver", "white", "yellow"}
)

#: canonical resource -> surface forms (singular; plurals are generated by adding "s").
#: "hbeam" is "H-beam" after hyphen protection in :func:`_prepare`.
RESOURCE_LEXICON: dict[str, tuple[str, ...]] = {
    "worker": ("worker", "construction worker"),
    "excavator": ("excavator",),
    "excavator_bucket": ("excavator bucket",),
    "dump_truck": ("dump truck", "dump"),  # "A white dump is loaded..." (truncated)
    "crane_truck": ("crane truck",),
    "crane": ("crane",),
    "tower_crane": ("tower crane",),
    "concrete_truck": ("concrete truck",),
    "truck": ("truck",),
    "drilling_rig": ("drilling",),  # annotators write "a green drilling" for a drilling rig
    "forklift": ("forklift",),
    "tarpaulin": ("tarpaulin",),
    "dust_protection": ("dust protection",),
    "h_beam": ("hbeam",),
    "rebar": ("rebar",),
    "mold": ("mold",),
    "wood_bar": ("wood bar", "wood"),
    "fence": ("fence",),
    "wood_fence": ("wood fence",),
    "safety_fence": ("safety fence",),
    "concrete_pipe": ("concrete pipe",),
    "concrete_pillar": ("concrete pillar",),
    "concrete_structure": ("concrete structure",),
    "concrete": ("concrete",),
    "foundation": ("foundation",),
    "temporary_building": ("temporary building", "temporary"),
    "container": ("container",),
    "structure": ("structure",),
    "safety_cone": ("safety cone",),
    "water_tank": ("water tank",),
    "material": ("material",),
}

_ONES = ["one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
_TEENS = [
    "ten",
    "eleven",
    "twelve",
    "thirteen",
    "fourteen",
    "fifteen",
    "sixteen",
    "seventeen",
    "eighteen",
    "nineteen",
]
_TENS = ["twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"]
NUMBER_WORDS: dict[str, int] = {
    **{w: i for i, w in enumerate(_ONES, 1)},
    **{w: i for i, w in enumerate(_TEENS, 10)},
}
TENS_WORDS: dict[str, int] = {w: 10 * i for i, w in enumerate(_TENS, 2)}

#: Reviewed single-token typo repairs. Only unambiguous cases seen in the data.
TOKEN_REPAIRS: dict[str, str] = {
    "sturcture": "structure",
    "rebara": "rebar",
    "plie": "pile",
    "loaced": "loaded",
    "builing": "building",
    "cocnrete": "concrete",
    "soi": "soil",
    "fivr": "five",
    "tweleve": "twelve",
    "elevens": "eleven",
    "thirteens": "thirteen",
    "wo": "two",
    "os": "of",
    "while": "white",  # "A while concrete truck"
}
#: Reviewed phrase repairs (regex on the lower-cased caption).
PHRASE_REPAIRS: tuple[tuple[str, str], ...] = (
    (r"\ba n orange\b", "an orange"),
    (r"\blocate d\b", "located"),
    (r"\bon on\b", "on"),
    (r"\bplace on\b", "placed on"),
)

#: Resource surface forms that are truncations of a longer name ("A white dump is loaded...").
#: They are accepted but recorded in ``repairs``.
TRUNCATED_ALIASES = frozenset(
    {("dump",), ("dumps",), ("temporary",), ("temporarys",), ("wood",), ("woods",)}
)

VERBS: dict[str, str] = {
    "located": "located",
    "installed": "installed",
    "embedded": "embedded",
    "placed": "placed",
    "digging": "digging",
    "drilling": "drilling",
    "lifting": "lifting",
    "pouring": "pouring",
    "putting": "putting",
    "loaded": "loaded",
    "covered": "covered",
    "covering": "covering",
    "empty": "empty",
    "on": "on",
}
PLACE_VERBS = frozenset({"located", "installed", "embedded", "placed", "on"})
EXTRA_TARGET_WORDS = frozenset(
    {"soil", "rock", "rocks", "road", "steel", "stone", "line", "and", "of", "pile", "piles"}
    | {"a", "an", "the"}
)
SPELLED_BACK = {"hbeam": "h-beam", "hbeams": "h-beams"}


def _plural(word: str) -> str:
    return word + "s"


def _build_lexicon() -> dict[tuple[str, ...], str]:
    lex: dict[tuple[str, ...], str] = {}
    for canon, forms in RESOURCE_LEXICON.items():
        for form in forms:
            words = tuple(form.split())
            lex[words] = canon
            lex[(*words[:-1], _plural(words[-1]))] = canon
    return lex


_LEXICON = _build_lexicon()
_MAX_PHRASE = max(len(k) for k in _LEXICON)
_TARGET_VOCAB = (
    EXTRA_TARGET_WORDS
    | COLOURS
    | {w for key in _LEXICON for w in key}
    | set(NUMBER_WORDS)
    | set(TENS_WORDS)
)

CATEGORY_NAMES: tuple[str, ...] = tuple(sorted(RESOURCE_LEXICON))
CATEGORY_IDS: dict[str, int] = {name: i for i, name in enumerate(CATEGORY_NAMES, start=1)}


def tokenize_caption(caption: str) -> list[str]:
    """Lower-cased tokens with 'H-beam' protected, punctuation removed and typo repairs applied."""
    return _prepare(caption)[0]


def parse_number_at(tokens: list[str], i: int) -> tuple[int, int] | None:
    """Public wrapper of the number-word parser: ``(value, tokens used)`` or ``None``."""
    return _number(tokens, i)


def find_resource(tokens: list[str], i: int) -> tuple[str, int] | None:
    """Longest resource phrase starting at ``tokens[i]``: ``(canonical name, tokens used)``."""
    return _longest_resource(tokens, i)


@dataclass
class CaptionFields:
    resource: str
    count: int | None
    count_unit: str | None  # "pile" | "item" | None (None only if neither a count nor "pile")
    colour: str | None
    state: str
    preposition: str | None
    target: str | None
    destination: str | None  # second object of "putting X in/on Y"
    repairs: list[str] = field(default_factory=list)


@dataclass
class ParseResult:
    fields: CaptionFields | None
    reason: str | None = None  # set iff fields is None


_CAMEL = re.compile(r"[a-z][A-Z]")


def _prepare(caption: str) -> tuple[list[str], list[str]]:
    """Lower-case, protect 'H-beam', drop punctuation, apply repairs. Returns (tokens, repairs)."""
    repairs: list[str] = []
    s = caption.lower()
    s = re.sub(r"h-beam", "hbeam", s)
    s = s.replace("-", " ")
    s = re.sub(r"[,.;:]", " ", s)
    s = " ".join(s.split())
    for pattern, replacement in PHRASE_REPAIRS:
        if re.search(pattern, s):
            s = re.sub(pattern, replacement, s)
            repairs.append(f"phrase:{pattern}->{replacement}")
    tokens = s.split()
    for i, tok in enumerate(tokens):
        fixed = TOKEN_REPAIRS.get(tok)
        if fixed is not None:
            repairs.append(f"typo:{tok}->{fixed}")
            tokens[i] = fixed
    return tokens, repairs


def _number(tokens: list[str], i: int) -> tuple[int, int] | None:
    """Parse a number word at ``i`` ('seven', 'twenty', 'twenty six') -> (value, tokens used)."""
    if i >= len(tokens):
        return None
    tok = tokens[i]
    if tok in NUMBER_WORDS:
        return NUMBER_WORDS[tok], 1
    if tok in TENS_WORDS:
        if (
            i + 1 < len(tokens)
            and tokens[i + 1] in NUMBER_WORDS
            and NUMBER_WORDS[tokens[i + 1]] < 10
        ):
            return TENS_WORDS[tok] + NUMBER_WORDS[tokens[i + 1]], 2
        return TENS_WORDS[tok], 1
    return None


def _longest_resource(tokens: list[str], i: int) -> tuple[str, int] | None:
    for length in range(min(_MAX_PHRASE, len(tokens) - i), 0, -1):
        canon = _LEXICON.get(tuple(tokens[i : i + length]))
        if canon is not None:
            return canon, length
    return None


def _target(tokens: list[str]) -> tuple[str | None, str | None]:
    """Validate a target phrase against the closed vocabulary. Returns (text, bad_word)."""
    words = list(tokens)
    while words and words[0] in ("a", "an", "the"):
        words.pop(0)
    if not words:
        return None, None
    for w in words:
        if w not in _TARGET_VOCAB:
            return None, w
    return " ".join(SPELLED_BACK.get(w, w) for w in words), None


def _split_once(tokens: list[str], seps: frozenset[str]) -> tuple[list[str], str | None, list[str]]:
    for i, tok in enumerate(tokens):
        if tok in seps:
            return tokens[:i], tok, tokens[i + 1 :]
    return tokens, None, []


def parse_caption(caption: str) -> ParseResult:
    """Parse one caption. Never raises; on failure returns ``ParseResult(None, reason)``."""
    if not caption.strip():
        return ParseResult(None, "empty_caption")
    if _CAMEL.search(caption):
        return ParseResult(None, "glued_captions")
    tokens, repairs = _prepare(caption)
    if sum(t in ("is", "are") for t in tokens) > 1:
        return ParseResult(None, "multiple_clauses")

    i = 0
    count: int | None = None
    unit: str | None = None
    if tokens and tokens[0] in ("a", "an"):
        count, i = 1, 1
    else:
        num = _number(tokens, 0)
        if num is not None:
            count, i = num[0], num[1]
    if i < len(tokens) and tokens[i] in ("pile", "piles"):
        unit = "pile"
        i += 1
        if i < len(tokens) and tokens[i] == "of":
            i += 1
    elif count is not None:
        unit = "item"

    colour = None
    if i < len(tokens) and tokens[i] in COLOURS:
        colour = "gray" if tokens[i] == "grey" else tokens[i]
        i += 1

    found = _longest_resource(tokens, i)
    if found is None:
        return ParseResult(None, "no_resource")
    resource, length = found
    surface = tuple(tokens[i : i + length])
    if surface in TRUNCATED_ALIASES:
        repairs.append(f"truncated:{' '.join(surface)}->{resource}")
    i += length
    if i < len(tokens) and tokens[i] in ("is", "are"):
        i += 1

    rest = tokens[i:]
    if not rest:
        return ParseResult(None, "no_predicate")
    verb = VERBS.get(rest[0])
    if verb is None:
        return ParseResult(None, f"unknown_predicate:{rest[0]}")
    body = rest[1:]
    prep: str | None = None
    target: str | None = None
    destination: str | None = None

    if verb == "empty":
        if body:
            return ParseResult(None, "trailing_words_after_empty")
    elif verb in PLACE_VERBS:
        if verb == "on":
            prep = "on"
        elif body and body[0] in ("on", "in"):
            prep, body = body[0], body[1:]
        elif body:
            repairs.append("missing_preposition")
        else:
            repairs.append("missing_target")
        target, bad = _target(body)
        if bad:
            return ParseResult(None, f"bad_target:{bad}")
    elif verb in ("loaded", "covered"):
        if body and body[0] == "with":
            prep, body = "with", body[1:]
        elif body:
            repairs.append("missing_preposition")
        target, bad = _target(body)
        if bad:
            return ParseResult(None, f"bad_target:{bad}")
    elif verb == "putting":
        first, sep, second = _split_once(body, frozenset({"in", "on"}))
        target, bad = _target(first)
        if bad:
            return ParseResult(None, f"bad_target:{bad}")
        if sep is not None:
            prep = sep
            destination, bad = _target(second)
            if bad:
                return ParseResult(None, f"bad_target:{bad}")
    else:  # digging, drilling, lifting, pouring, covering
        if body and body[0] in ("on", "in"):
            prep, body = body[0], body[1:]
        target, bad = _target(body)
        if bad:
            return ParseResult(None, f"bad_target:{bad}")

    return ParseResult(
        CaptionFields(
            resource=resource,
            count=count,
            count_unit=unit,
            colour=colour,
            state=verb,
            preposition=prep,
            target=target,
            destination=destination,
            repairs=repairs,
        )
    )


@dataclass
class CoverageReport:
    n_annotations: int = 0
    n_parsed: int = 0
    n_unparsed: int = 0
    n_empty: int = 0
    n_with_repairs: int = 0
    n_with_count: int = 0
    failure_reasons: dict[str, int] = field(default_factory=dict)
    failure_examples: dict[str, list[str]] = field(default_factory=dict)
    resource_counts: dict[str, int] = field(default_factory=dict)
    state_counts: dict[str, int] = field(default_factory=dict)
    n_distinct_captions: int = 0
    n_distinct_parsed: int = 0

    @property
    def coverage(self) -> float:
        """Parsed / non-empty annotations."""
        denom = self.n_annotations - self.n_empty
        return self.n_parsed / denom if denom else 0.0

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["coverage"] = self.coverage
        return d


def apply_caption_fields(ds: Dataset) -> CoverageReport:
    """Fill ``category_id`` / ``fields`` for every annotation and set the ``unparsed`` flag.

    Idempotent: previous parse results are cleared first. Empty captions keep their
    ``empty_caption`` flag only (they are not counted as parse failures).
    """
    ds.categories = [CategoryRecord(id=i, name=n) for n, i in CATEGORY_IDS.items()]
    report = CoverageReport()
    cache: dict[str, ParseResult] = {}
    resources: Counter[str] = Counter()
    states: Counter[str] = Counter()
    reasons: Counter[str] = Counter()
    examples: dict[str, list[str]] = {}
    distinct: set[str] = set()
    distinct_parsed: set[str] = set()

    for a in ds.annotations:
        report.n_annotations += 1
        a.flags = [f for f in a.flags if f != FLAG_UNPARSED]
        a.category_id, a.fields = None, None
        if not a.caption:
            report.n_empty += 1
            continue
        distinct.add(a.caption)
        res = cache.get(a.caption)
        if res is None:
            res = cache[a.caption] = parse_caption(a.caption)
        if res.fields is None:
            reason = res.reason or "unknown"
            report.n_unparsed += 1
            reasons[reason] += 1
            examples.setdefault(reason.split(":")[0], [])
            if (
                a.caption not in examples[reason.split(":")[0]]
                and len(examples[reason.split(":")[0]]) < 5
            ):
                examples[reason.split(":")[0]].append(a.caption)
            a.flags.append(FLAG_UNPARSED)
            continue
        f = res.fields
        a.category_id = CATEGORY_IDS[f.resource]
        a.fields = asdict(f)
        report.n_parsed += 1
        distinct_parsed.add(a.caption)
        resources[f.resource] += 1
        states[f.state] += 1
        report.n_with_repairs += bool(f.repairs)
        report.n_with_count += f.count is not None

    report.failure_reasons = dict(sorted(reasons.items()))
    report.failure_examples = dict(sorted(examples.items()))
    report.resource_counts = dict(resources.most_common())
    report.state_counts = dict(states.most_common())
    report.n_distinct_captions = len(distinct)
    report.n_distinct_parsed = len(distinct_parsed)
    return report


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Fill structured caption fields and categories.")
    p.add_argument(
        "--annotations", type=Path, required=True, help="annotations.json from via_parse"
    )
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--report", type=Path, help="coverage_report.json")
    args = p.parse_args(argv)
    ds = Dataset.load(args.annotations)
    report = apply_caption_fields(ds)
    ds.save(args.out)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(
            json.dumps(report.to_dict(), indent=1, sort_keys=True) + "\n", encoding="utf-8"
        )
    print(
        f"annotations {report.n_annotations}: parsed {report.n_parsed}, "
        f"unparsed {report.n_unparsed}, empty {report.n_empty}; coverage {report.coverage:.4f}"
    )
    for reason, n in report.failure_reasons.items():
        print(f"  {reason}: {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
